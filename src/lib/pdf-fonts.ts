const FALLBACK = 0x3f;

export class PdfFont {
  readonly bbox: [number, number, number, number];
  readonly compressed: Buffer;
  readonly descent: number;
  readonly ascent: number;
  readonly raw: Buffer;
  readonly units: number;

  private readonly advances: number[];
  private readonly cmap = new Map<number, number>();

  constructor(
    readonly name: string,
    data: string
  ) {
    this.compressed = Buffer.from(data, "base64");
    this.raw = inflateSync(this.compressed);
    const tables = this.tables();
    const head = tables.get("head")!;
    const hhea = tables.get("hhea")!;
    this.units = this.raw.readUInt16BE(head + 18);
    this.bbox = [36, 38, 40, 42].map((at) => this.raw.readInt16BE(head + at)) as PdfFont["bbox"];
    this.ascent = this.raw.readInt16BE(hhea + 4);
    this.descent = this.raw.readInt16BE(hhea + 6);

    const hmtx = tables.get("hmtx")!;
    const metrics = this.raw.readUInt16BE(hhea + 34);
    this.advances = Array.from({ length: metrics }, (_, i) => this.raw.readUInt16BE(hmtx + i * 4));
    this.readCmap(tables.get("cmap")!);
  }

  private tables() {
    const found = new Map<string, number>();
    const count = this.raw.readUInt16BE(4);
    for (let i = 0; i < count; i++) {
      const at = 12 + i * 16;
      found.set(this.raw.toString("latin1", at, at + 4), this.raw.readUInt32BE(at + 8));
    }
    return found;
  }

  private readCmap(table: number) {
    const records = this.raw.readUInt16BE(table + 2);
    for (let i = 0; i < records; i++) {
      const at = table + 4 + i * 8;
      if (this.raw.readUInt16BE(at) !== 3 || this.raw.readUInt16BE(at + 2) !== 1) continue;
      const sub = table + this.raw.readUInt32BE(at + 4);
      const segments = this.raw.readUInt16BE(sub + 6) / 2;
      const ends = sub + 14;
      const starts = ends + segments * 2 + 2;
      const deltas = starts + segments * 2;
      for (let s = 0; s < segments; s++) {
        const [first, last] = [this.raw.readUInt16BE(starts + s * 2), this.raw.readUInt16BE(ends + s * 2)];
        if (first === 0xffff) continue;
        for (let code = first; code <= last; code++) {
          this.cmap.set(code, (code + this.raw.readInt16BE(deltas + s * 2)) & 0xffff);
        }
      }
    }
  }

  /** The code point actually drawn: the character itself, or "?" when the font lacks it. */
  drawn(code: number) {
    return this.cmap.has(code) ? code : FALLBACK;
  }

  glyph(code: number) {
    return this.cmap.get(this.drawn(code))!;
  }

  /** Advance width in 1/1000 em. */
  advance(glyph: number) {
    const units = this.advances[Math.min(glyph, this.advances.length - 1)]!;
    return Math.round((units * 1000) / this.units);
  }

  width(text: string, size: number) {
    let total = 0;
    for (const ch of text) total += this.advance(this.glyph(ch.codePointAt(0)!));
    return (total * size) / 1000;
  }
}

export const MEDIUM = new PdfFont("PlusJakartaSans-Medium", MEDIUM_DATA);
export const BOLD = new PdfFont("PlusJakartaSans-Bold", BOLD_DATA);

export const textWidth = (text: string, size: number, bold = false) => (bold ? BOLD : MEDIUM).width(text, size);
